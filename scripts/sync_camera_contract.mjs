// Camera metadata is independent of the phone's pinned preview renderer.
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const canonical=v=>Array.isArray(v)?'['+v.map(canonical).join(',')+']':v&&typeof v==='object'?'{'+Object.keys(v).sort().map(k=>JSON.stringify(k)+':'+canonical(v[k])).join(',')+'}':JSON.stringify(v);
export async function copyCameraMetadata(staging,root){
 const catalog=JSON.parse(await readFile(path.join(staging,'assets/films/catalog.json')));
 for(const film of catalog.entries){
  const original=film.icon;film.icon=`assets/films/camera-icons/${film.id}.png`;
  await mkdir(path.dirname(path.join(root,film.icon)),{recursive:true});
  await copyFile(path.join(staging,original),path.join(root,film.icon));
 }
 delete catalog.hash;catalog.hash=createHash('sha256').update(canonical(catalog)).digest('hex');
 const contract=await readFile(path.join(staging,'assets/films/companion-v1.json'));
 const source=JSON.parse(await readFile(path.join(staging,'assets/films/source-manifest.json')));
 source.catalogHash=catalog.hash;
 await writeFile(path.join(root,'assets/films/camera-catalog.json'),JSON.stringify(catalog,null,2)+'\n');
 await writeFile(path.join(root,'assets/films/camera-contract.json'),contract);
 await writeFile(path.join(root,'assets/films/camera-source-manifest.json'),JSON.stringify(source,null,2)+'\n');
 await writeFile(path.join(root,'lib/camera/companion/generated_camera_contract.dart'),`// Generated by scripts/sync_camera_contract.mjs. Do not edit.\nconst cameraContractJson = r'''${JSON.stringify(JSON.parse(contract))}''';\nconst cameraCatalogHash = '${catalog.hash}';\nconst cameraRendererHash = '${catalog.rendererHash}';\nconst cameraBuiltinFilmIds = <int>{${catalog.entries.map(f=>f.id).join(',')}};\n`);
 return {catalogHash:catalog.hash,rendererHash:catalog.rendererHash,films:catalog.entries.length};
}
async function copyLeicaCameraProfile(source,root){
 const m10v=path.resolve(source);
 const generator=path.join(m10v,'scripts/read_gr3_gremote_camera_metadata.mjs');
 const catalog=JSON.parse(execFileSync(process.execPath,[generator,'--catalog'],{cwd:m10v,encoding:'utf8'}));
 const {hash,...identity}=catalog;
 const contractBytes=await readFile(path.join(m10v,'contracts/companion-v1.json'));
 const contract=JSON.parse(contractBytes);
 const ids=[331,332,333,334];
 if(hash!==createHash('sha256').update(canonical(identity)).digest('hex')||
    !/^[a-f0-9]{64}$/.test(catalog.rendererHash)||contract.maximumFilmId!==334||
    ids.some(id=>!catalog.entries.some(f=>f.id===id&&f.group==='影像'&&f.icon===`assets/films/camera-icons/${id}.png`))){
  throw Error('M10V Leica camera profile is incomplete');
 }
 const icons=await Promise.all(ids.map(id=>readFile(path.join(m10v,`web/gr3/film-icons/${id}-large.png`))));
 const profile=path.join(root,'assets/films/camera-profiles');
 for(let i=0;i<ids.length;i++){
  await writeFile(path.join(root,`assets/films/camera-icons/${ids[i]}.png`),icons[i]);
 }
 await writeFile(path.join(profile,'leica-gr3-catalog.json'),JSON.stringify(catalog,null,2)+'\n');
 await writeFile(path.join(profile,'leica-gr3-contract.json'),contractBytes);
 await writeFile(path.join(root,'lib/camera/companion/generated_leica_camera_contract.dart'),
  `// Generated by scripts/sync_camera_contract.mjs --leica-profile. Do not edit.\nconst leicaCameraContractJson =\n    r'''${JSON.stringify(contract)}''';\nconst leicaCameraCatalogHash =\n    '${hash}';\nconst leicaCameraRendererHash =\n    '${catalog.rendererHash}';\n`);
 return {catalogHash:hash,rendererHash:catalog.rendererHash,films:catalog.entries.length};
}

if(process.argv[1]===fileURLToPath(import.meta.url)){
 const root=fileURLToPath(new URL('..',import.meta.url));
 const result=process.argv[2]==='--leica-profile'
  ?await copyLeicaCameraProfile(process.argv[3],root)
  :await copyCameraMetadata(process.argv[2],root);
 console.log(JSON.stringify(result));
}
