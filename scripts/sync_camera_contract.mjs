// Camera metadata is independent of the phone's pinned preview renderer.
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const canonical=v=>Array.isArray(v)?'['+v.map(canonical).join(',')+']':v&&typeof v==='object'?'{'+Object.keys(v).sort().map(k=>JSON.stringify(k)+':'+canonical(v[k])).join(',')+'}':JSON.stringify(v);
export async function copyCameraMetadata(staging,root){
 const catalog=JSON.parse(await readFile(path.join(staging,'assets/films/catalog.json')));
 for(const film of catalog.entries){
  const original=film.icon;film.icon=`assets/films/camera-icons/${film.id}.png`;
  await mkdir(path.dirname(path.join(root,film.icon)),{recursive:true});
  await copyFile(path.join(staging,original),path.join(root,film.icon));
 }
 delete catalog.hash;catalog.hash=createHash('sha256').update(canonical(catalog)).digest('hex');
 const contract=await readFile(path.join(staging,'assets/films/companion-v1.json'));
 const source=JSON.parse(await readFile(path.join(staging,'assets/films/source-manifest.json')));
 source.catalogHash=catalog.hash;
 await writeFile(path.join(root,'assets/films/camera-catalog.json'),JSON.stringify(catalog,null,2)+'\n');
 await writeFile(path.join(root,'assets/films/camera-contract.json'),contract);
 await writeFile(path.join(root,'assets/films/camera-source-manifest.json'),JSON.stringify(source,null,2)+'\n');
 await writeFile(path.join(root,'lib/camera/companion/generated_camera_contract.dart'),`// Generated by scripts/sync_camera_contract.mjs. Do not edit.\nconst cameraContractJson = r'''${JSON.stringify(JSON.parse(contract))}''';\nconst cameraCatalogHash = '${catalog.hash}';\nconst cameraRendererHash = '${catalog.rendererHash}';\nconst cameraBuiltinFilmIds = <int>{${catalog.entries.map(f=>f.id).join(',')}};\n`);
 return {catalogHash:catalog.hash,rendererHash:catalog.rendererHash,films:catalog.entries.length};
}
if(process.argv[1]===fileURLToPath(import.meta.url))console.log(JSON.stringify(await copyCameraMetadata(process.argv[2],fileURLToPath(new URL('..',import.meta.url)))));
