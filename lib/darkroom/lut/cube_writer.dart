/// Writes a 3D `.cube` LUT with the red index varying fastest.
String writeCube({
  required String title,
  required int size,
  required List<double> Function(double r, double g, double b) map,
}) {
  final buffer = StringBuffer()
    ..writeln('# gremote original look, generated by tool/generate_luts.dart')
    ..writeln('TITLE "$title"')
    ..writeln('LUT_3D_SIZE $size')
    ..writeln('DOMAIN_MIN 0.0 0.0 0.0')
    ..writeln('DOMAIN_MAX 1.0 1.0 1.0');
  final last = size - 1;
  for (var b = 0; b < size; b++) {
    for (var g = 0; g < size; g++) {
      for (var r = 0; r < size; r++) {
        final out = map(r / last, g / last, b / last);
        buffer.writeln(out.map(_format).join(' '));
      }
    }
  }
  return buffer.toString();
}

String _format(double value) {
  final clamped = value.isNaN ? 0.0 : value.clamp(0.0, 1.0).toDouble();
  // Adding 0.0 normalises -0.0 so the text never contains "-0.000000".
  return (clamped + 0.0).toStringAsFixed(6);
}
